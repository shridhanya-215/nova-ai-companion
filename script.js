// 1. Get the HTML elements we need

const chatMessages = document.getElementById("chatMessages");
const chatForm = document.getElementById("chatForm");
const userInput = document.getElementById("userInput");

const suggestionButtons = document.querySelectorAll(
    ".suggestion-button"
);


// 2. Display a message in the chat window

function addMessage(text, sender) {
    const message = document.createElement("div");

    message.classList.add("message");

    if (sender === "nova") {
        message.classList.add("nova-message");
    } else {
        message.classList.add("user-message");
    }

    // Create a sender label

    const label = document.createElement("span");
    label.classList.add("message-label");

    label.textContent = sender === "nova" ? "NOVA" : "YOU";

    // Create the message text

    const paragraph = document.createElement("p");
    paragraph.textContent = text;

    message.appendChild(label);
    message.appendChild(paragraph);

    chatMessages.appendChild(message);

    // Scroll to the newest message

    chatMessages.scrollTop = chatMessages.scrollHeight;
}


// 3. Generate a response to a message

function generateResponse(question) {
    const q = question.toLowerCase().trim();

    if (
        q.includes("hello") ||
        q.includes("hi") ||
        q.includes("hey")
    ) {
        return "Hello! I'm Nova, your digital companion concept. What would you like to explore today?";
    }

    if (
        q.includes("what can you do") ||
        q.includes("capabilit") ||
        q.includes("features")
    ) {
        return "I can demonstrate an interactive chat interface, respond to sample prompts, and introduce ideas about digital companions. In this version, my responses are predefined rather than generated by a live AI model.";
    }

    if (
        q.includes("hologram") ||
        q.includes("holographic") ||
        q.includes("pepper")
    ) {
        return "A true hologram reconstructs light to create a three-dimensional optical image. Pepper's Ghost is a different technique that uses reflection to create a floating-image illusion. Both are interesting starting points for researching display possibilities.";
    }

    if (
        q.includes("learn") ||
        q.includes("teach") ||
        q.includes("study")
    ) {
        return "Let's explore something step by step! Start with a question, understand the underlying concept, and test your understanding with a small experiment. What topic interests you?";
    }

    if (
        q.includes("who are you") ||
        q.includes("your name")
    ) {
        return "I'm Nova, a concept for an interactive digital companion. My visual interface and conversation flow are being explored through this browser prototype.";
    }

    if (
        q.includes("artificial intelligence") ||
        q.includes("machine learning") ||
        q.includes(" ai ")
    ) {
        return "Artificial intelligence allows computer systems to perform tasks such as understanding language, recognising patterns, and generating responses. This prototype currently uses scripted replies; integrating a real AI model would be a separate development step.";
    }

    if (
        q.includes("3d") ||
        q.includes("three dimensional") ||
        q.includes("character")
    ) {
        return "A 3D companion could use a model created in software such as Blender, with animation added to make its expressions and movements feel more natural. This prototype currently uses CSS-based visual effects rather than a 3D model.";
    }

    if (
        q.includes("project") ||
        q.includes("roadmap") ||
        q.includes("build")
    ) {
        return "The project roadmap begins with this interactive interface, then explores 3D character modelling, conversational AI integration, and possible physical display techniques. Each stage would need to be built and tested.";
    }

    if (
        q.includes("thank")
    ) {
        return "You're welcome! Curiosity is a great place to start. Keep experimenting, testing ideas, and learning from the results.";
    }

    return "That's an interesting question! My current prototype has a limited set of predefined responses, so I may not understand every message yet. A future version could connect to a real conversational AI model.";
}


// 4. Handle a conversation

function handleConversation(question) {
    const cleanedQuestion = question.trim();

    if (!cleanedQuestion) {
        return;
    }

    // Display the user's message

    addMessage(cleanedQuestion, "user");

    // Get Nova's predefined response

    const response = generateResponse(cleanedQuestion);

    // Show the response after a short delay

    window.setTimeout(function () {
        addMessage(response, "nova");
    }, 350);
}


// 5. Handle the chat form

chatForm.addEventListener("submit", function (event) {
    event.preventDefault();

    const question = userInput.value.trim();

    if (!question) {
        return;
    }

    handleConversation(question);

    // Clear the input field

    userInput.value = "";
    userInput.focus();
});


// 6. Handle suggested prompt buttons

suggestionButtons.forEach(function (button) {
    button.addEventListener("click", function () {
        const question = button.dataset.question;

        handleConversation(question);
    });
});


// 7. Log that the interaction script has loaded

console.log("Nova interaction engine loaded successfully.");
console.log("Mode: predefined responses — no live AI connected.");
